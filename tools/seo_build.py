#!/usr/bin/env python3
"""
AI Pulse – search and AI-engine build step.

Run from the repo root before every publish:

    python3 tools/seo_build.py          # update pages, sitemap.xml
    python3 tools/seo_build.py --check  # exit 1 if anything is out of date

What it does (safe to run any number of times; it only rewrites what is stale):
  1. Gives every story an id, so each story has its own link (#story-slug).
  2. Keeps a permanent page for today's issue at archive/issue-D-month-YYYY.html,
     mirrored from index.html, so AI engines and readers can cite a link that
     never changes. (This is the same file the nightly archive step creates.)
  3. Writes a page-specific title, description, canonical link, social preview
     text and NewsArticle structured data (JSON-LD) into each page's <head>,
     between the AIPULSE-SEO markers.
  4. Adds the "Published by" line with links to the About page in the footer.
  5. Regenerates sitemap.xml.

It never changes story text, numbers, sources or layout.
"""
import html
import json
import pathlib
import re
import sys
from datetime import date

from bs4 import BeautifulSoup

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = "https://ai-pulse.in"
ABOUT_URL = f"{SITE}/about.html"
ABOUT_UPDATED = "2026-10-29"
LOGO = f"{SITE}/assets/icons/icon-512.png"
OG_IMAGE = f"{SITE}/assets/images/og-image.png"
PUBLISHER_NAME = "Yash Jain"
PUBLISHER_LINKEDIN = "https://www.linkedin.com/in/yashjain14/"

SEO_START = "<!-- AIPULSE-SEO:START (generated by tools/seo_build.py; do not edit by hand) -->"
SEO_END = "<!-- AIPULSE-SEO:END -->"
SEO_BLOCK_RE = re.compile(r"[ \t]*<!-- AIPULSE-SEO:START.*?<!-- AIPULSE-SEO:END -->\n?", re.S)
GENERIC_TAG_RE = re.compile(
    r'^[ \t]*<(?:meta (?:name="description"|property="og:title"|property="og:description"|'
    r'property="og:url"|property="og:type"|name="twitter:title"|name="twitter:description")'
    r'|link rel="canonical")[^>]*>[ \t]*\n',
    re.M,
)
BYLINE_RE = re.compile(r'\n[ \t]*<p class="footer-byline">.*?</p>', re.S)
FOOTER_NOTE_RE = re.compile(r'([ \t]*)(<p class="footer-note">.*?</p>)', re.S)
STATE_RE = re.compile(r"<!-- AIPULSE-STATE (\{.*?\}) -->")
ISSUE_FILE_RE = re.compile(r"^issue-(\d{1,2})-([a-z]+)-(\d{4})\.html$")

MONTHS = ["january", "february", "march", "april", "may", "june", "july",
          "august", "september", "october", "november", "december"]
MONTH_ALIASES = {m[:3]: i + 1 for i, m in enumerate(MONTHS)}
MONTH_ALIASES.update({m: i + 1 for i, m in enumerate(MONTHS)})
MONTH_ALIASES["sept"] = 9
SLUG_STOPWORDS = {"a", "an", "the", "and", "or", "as", "of", "to", "that", "which", "its", "it", "is",
                  "in", "on", "for", "with", "from", "by", "at", "while", "after", "but", "so", "than"}

# Shown in the <head> block on every page: anchor offset under the sticky nav,
# and the footer "Published by" line.
SEO_CSS = (
    ".story{scroll-margin-top:96px}"
    ".footer-byline{flex-basis:100%;font-family:'Carlito',sans-serif;font-size:13px;line-height:1.6;"
    "color:var(--text-muted);margin-top:-16px}"
    ".footer-byline a{color:var(--text-secondary);text-decoration:underline;"
    "text-decoration-color:var(--border-strong);text-underline-offset:3px;transition:color .2s ease}"
    ".footer-byline a:hover{color:var(--accent)}"
)


# ---------------------------------------------------------------- helpers

def squash(text):
    return " ".join((text or "").split())


def trim(text, limit):
    text = squash(text)
    if len(text) <= limit:
        return text
    cut = text[:limit]
    i = cut.rfind(", ")
    if i < limit * 0.6:
        i = cut.rfind(" ")
    return cut[:i].rstrip(" ,;:–") + "…"


def lead_clause(headline):
    """First clause of the lead headline, for the <title>."""
    headline = squash(headline)
    cut = len(headline)
    for sep in (", ", " as ", " while ", " after ", " – ", "; "):
        i = headline.find(sep)
        if 30 <= i < cut:
            cut = i
    clause = headline[:cut].rstrip(" ,;:")
    if len(clause) > 110:
        clause = clause[:110].rsplit(" ", 1)[0].rstrip(" ,;:–") + "…"
    return clause


def slugify(text, max_len=60):
    text = squash(text).lower().replace("&", " and ")
    text = re.sub(r"[’'`]", "", text)
    text = re.sub(r"[^a-z0-9]+", "-", text).strip("-")
    if len(text) > max_len:
        text = text[:max_len].rsplit("-", 1)[0]
    words = text.split("-")
    while len(words) > 3 and words[-1] in SLUG_STOPWORDS:
        words.pop()
    return "-".join(words) or "story"


def fmt_date(d):
    return f"{d.day} {MONTHS[d.month - 1].capitalize()} {d.year}"


def issue_filename(d):
    return f"issue-{d.day}-{MONTHS[d.month - 1]}-{d.year}.html"


def date_from_filename(name):
    m = ISSUE_FILE_RE.match(name)
    if not m:
        return None
    month = MONTH_ALIASES.get(m.group(2))
    if not month:
        return None
    try:
        return date(int(m.group(3)), month, int(m.group(1)))
    except ValueError:
        return None


def esc(value):
    return html.escape(value, quote=True)


def json_ld(data):
    text = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    return text.replace("</", "<\\/")


def read_state(text):
    m = STATE_RE.search(text)
    if not m:
        return {}
    try:
        return json.loads(m.group(1))
    except json.JSONDecodeError:
        return {}


def previous_date_modified(text):
    m = SEO_BLOCK_RE.search(text)
    if not m:
        return None
    found = re.search(r'"dateModified":\s*"([^"]+)"', m.group(0))
    return found.group(1) if found else None


# ---------------------------------------------------------------- reading pages

def extract_issue(text):
    soup = BeautifulSoup(text, "lxml")
    h1 = soup.find("h1")
    stories = []
    for art in soup.select("article.story"):
        h2 = art.find("h2")
        first_p = art.select_one(".plain-text p")
        src = art.select_one(".source-block a")
        src_href = src.get("href", "") if src else ""
        stories.append({
            "id": art.get("id"),
            "headline": squash(h2.get_text()) if h2 else "",
            "summary": squash(first_p.get_text()) if first_p else "",
            "sectors": [squash(t.get_text()) for t in art.select(".story-meta .tag")],
            "source_name": squash(src.get_text()) if src else "",
            "source_url": src_href if src_href.startswith("http") else "",
        })
    return {"h1": squash(h1.get_text()) if h1 else "", "stories": stories}


def add_story_ids(text):
    """Give each <article class="story"> a stable id based on its headline."""
    info = extract_issue(text)
    taken = set(re.findall(r'\sid="([^"]+)"', text))
    openings = list(re.finditer(r'<article class="(story(?:\s[^"]*)?)"([^>]*)>', text))
    if len(openings) != len(info["stories"]):
        return text, [s["id"] or "" for s in info["stories"]]
    ids, out, pos = [], [], 0
    for match, story in zip(openings, info["stories"]):
        cls, attrs = match.group(1), match.group(2)
        existing = re.search(r'\sid="([^"]+)"', attrs)
        if existing:
            ids.append(existing.group(1))
            continue
        base = slugify(story["headline"])
        slug, n = base, 2
        while slug in taken:
            slug, n = f"{base}-{n}", n + 1
        taken.add(slug)
        ids.append(slug)
        out.append(text[pos:match.start()])
        out.append(f'<article class="{cls}" id="{slug}"{attrs}>')
        pos = match.end()
    out.append(text[pos:])
    return "".join(out), ids


# ---------------------------------------------------------------- permanent page for today's issue

def back_link_css():
    sample = (ROOT / "archive" / "issue-6-june-2026.html").read_text(encoding="utf-8")
    m = re.search(r"    \.back-link \{.*?\.back-link:hover svg \{ transform: translateX\(-3px\); \}\n", sample, re.S)
    if not m:
        raise RuntimeError("could not find the .back-link CSS block in archive/issue-6-june-2026.html")
    return m.group(0)


def mirror_from_index(index_text):
    """Apply the nightly archive transformation to a copy of index.html."""
    t = SEO_BLOCK_RE.sub("", index_text)
    t = BYLINE_RE.sub("", t)
    steps = [
        (re.compile(r"^<!-- AIPULSE-STATE .*?-->\n", re.M), ""),
        (re.compile(r"    \.archive-link \{.*?\.archive-link:hover svg \{ transform: translateX\(3px\); \}\n", re.S),
         back_link_css().replace("\\", "\\\\")),
        (re.compile(r'\n[ \t]*<a href="archive/index.html" class="archive-link">.*?</a>\s*'
                    r'<button id="signupBtn"[^>]*>.*?</button>', re.S),
         '\n        <a href="index.html" class="back-link">\n'
         '          <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">'
         '<path d="M19 12H5M11 19l-7-7 7-7"/></svg>\n'
         '          <span>Back to archive</span>\n'
         '        </a>'),
        (re.compile(r'\n[ \t]*<button id="footerSignupBtn"[^>]*>.*?</button>', re.S), ""),
    ]
    for pattern, repl in steps:
        t, n = pattern.subn(repl, t, count=1)
        if n != 1:
            raise RuntimeError(f"archive step did not match: {pattern.pattern[:60]}…")
    return t


